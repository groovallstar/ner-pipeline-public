"""LLM 라벨러용 공통 NER 프롬프트 템플릿.

canonical 명칭(PER/LOC/ORG/DAT/PROD/EVT)으로 정렬된 한국어 NER:
- 6개 엔티티 타입: PER, LOC, ORG, DAT, PROD, EVT (KLUE의 TI·QT는 드롭)
- PER/DAT 는 KLUE NER 가이드라인 유지(조사 제외·음절 경계·복합 묶음)
- LOC/ORG/시설 경계는 한국어 전용 규칙을 따른다
  (`docs/manual/data/korean-entity-labeling-rules.md`): 인공 시설·venue 는
  비-entity(drop), LOC=행정·자연·주소(지명 표면형은 팀·환유여도 LOC),
  ORG=정부·행정·공공·정치 기관만 + 환유 정부건물명. 민간 회사·언론/방송·
  스포츠 구단/리그·군·법원/검찰·종교조직은 비-entity(drop)
- PROD/EVT 경계는 canonical 스키마(§1·§2.2·§3·§3.1~§3.4·§5.3) 기준을 따른다
  (운영 리그=ORG 아님·경기·대회=EVT, 명명 탈것=PROD vs 사건 head=EVT,
  eponymy 작품↔인물 치환, 법령·시대구분·설비 호기는 비-entity)
- EVT 에는 고유명 없는 회의·회견·의식도 든다 (§5.3 R2). 회의·회견은 **닫힌 목록이
  아니라 head 원칙** 이다 — `회의`·`회담`·`간담회` 등 canonical head 로 끝나면
  제도화·임의 개최를 불문하고 EVT 다. 단 상설 조직체(`위원회`·`협의회`)는 ORG 이고,
  head 단독(`회의`·`회담`)은 축2 generic 이라 비-entity 다. 의식(`시상식`·`개막식`)만
  어휘 목록으로 남는다 — `식`·`쇼` 는 1 글자라 형태로 어휘 경계를 가를 수 없다.
  장소·문서 파생어는 비-entity 이고, 고유명은 그 행사 *명칭의 일부* 일 때만 span 에
  포함한다 (`긴급 기자회견`→`기자회견` vs `MBC 연예대상` 통째)
- EVT 에는 **고유명 + 사건 head** 복합도 든다 (§5.3 축1-복합). 고유명이 조사 없이
  head 앞에 오면 그 전체가 EVT 이고(`세월호 참사`·`보스턴 마라톤`), 고유명이 없으면
  축2 generic 이라 비-entity 다(`교통사고`). 조사가 붙은 앞말은 수식이 아니라 문장
  성분이라 span 밖이다(`파리에서 테러`→`테러`). 라벨이 겹칠 수 없으므로 같은 고유명을
  EVT span 과 LOC·ORG 로 두 번 잡지 않는다 — 이 조건이 축3 경계를 가른다.
"""


